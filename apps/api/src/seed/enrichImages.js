import 'dotenv/config';
import mongoose from 'mongoose';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { env } from '../config/env.js';
import Dish from '../models/Dish.js';

const CURATED_NAMES = [
  'Litti Chokha', 'Dal Baati Churma', 'Bhutte ka Kees', 'Ker Sangri', 'Siddu',
  'Erissery', 'Kori Rotti', 'Macher Jhol', 'Chingudi Chhechadi', 'Handvo'
];

const sleep = (ms) => new Promise(r => setTimeout(r, ms));

async function wikiSearch(q) {
  const url = 'https://en.wikipedia.org/w/api.php?action=query&generator=search&gsrsearch=' +
    encodeURIComponent(q) + '&gsrlimit=1&prop=pageimages&piprop=thumbnail&pithumbsize=900&format=json&origin=*';
  for (let attempt = 0; attempt < 2; attempt++) {
    try {
      const res = await fetch(url, {
        signal: AbortSignal.timeout(12000),
        headers: { 'User-Agent': 'SwaadCartCapstone/1.0 (educational project)' }
      });
      if (!res.ok) throw new Error('HTTP ' + res.status);
      const j = await res.json();
      const page = j.query && j.query.pages ? Object.values(j.query.pages)[0] : null;
      const img = page && page.thumbnail && page.thumbnail.source;
      if (img) return img;
      return null;
    } catch {
      await sleep(500 * (attempt + 1));
    }
  }
  return null;
}

async function wikiImage(name) {
  const variants = [name + ' food', name + ' dish', name];
  for (const q of variants) {
    const img = await wikiSearch(q);
    if (img) return img;
    await sleep(100);
  }
  return null;
}

function pickFallback(pool, name, diet) {
  const candidates = pool.filter(p => p.diet === diet);
  const list = candidates.length ? candidates : pool;
  if (!list.length) return null;
  let hash = 0;
  for (const ch of name) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return list[hash % list.length].url;
}

async function main() {
  await mongoose.connect(env.MONGODB_URI);
  const dishes = await Dish.find({}).select('name diet slots imageUrl').lean();
  const targets = [...dishes.map(d => ({ name: d.name, diet: d.diet }))];
  for (const name of CURATED_NAMES) targets.push({ name, diet: 'veg' });

  const unique = [...new Map(targets.map(t => [t.name, t])).values()];
  const found = new Map();
  const pool = [];
  let done = 0;

  for (const t of unique) {
    const url = await wikiImage(t.name);
    if (url) {
      found.set(t.name, url);
      pool.push({ name: t.name, diet: t.diet, url });
    }
    done++;
    if (done % 20 === 0) console.log(`  ${done}/${unique.length} looked up (${found.size} images)`);
    await sleep(120);
  }

  const images = {};
  for (const t of unique) {
    images[t.name] = found.get(t.name) || pickFallback(pool, t.name, t.diet);
  }

  const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../data');
  await fs.mkdir(dir, { recursive: true });
  const header = '// Auto-generated by src/seed/enrichImages.js — do not edit by hand.\n// Image files are hosted by Wikimedia Commons (free, hotlink-friendly).\nexport const dishImages = ';
  await fs.writeFile(path.join(dir, 'dishImages.js'), header + JSON.stringify(images, null, 2) + ';\n', 'utf8');

  const ops = Object.entries(images)
    .filter(([name]) => dishes.some(d => d.name === name))
    .map(([name, imageUrl]) => ({ updateOne: { filter: { name }, update: { $set: { imageUrl } } } }));
  if (ops.length) await Dish.bulkWrite(ops);

  console.log(`Done. ${found.size}/${unique.length} real images, ${unique.length - found.size} fallbacks. DB updated: ${ops.length}`);
  await mongoose.disconnect();
}

main().catch(async (e) => {
  console.error(e);
  try { await mongoose.disconnect(); } catch {}
  process.exit(1);
});
